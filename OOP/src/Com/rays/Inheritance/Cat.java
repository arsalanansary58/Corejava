package Com.rays.Inheritance;
public class Cat extends Animal{

	private String colour;
	private String name;
	
	public void setname(String name) {
		this.name=name;
	}
	public String getname() {
		return name;
	}
	public void setcolour(String colour) {
		this.colour=colour;
	}
	public String getcolour() {
		return colour;
	}
	
	
}
